const GENERIC_PLACEHOLDER = '20 123 45678';

/**
 * Returns a local-format example for the selected country (ISO 3166-1 alpha-2).
 * Falls back to a generic digit pattern when unknown.
 */
export function getRegistrationPhonePlaceholder(
  countryIso: string | undefined | null
): string {
  if (!countryIso?.trim()) return GENERIC_PLACEHOLDER;
  return PLACEHOLDERS_BY_ISO[countryIso.toUpperCase()] ?? GENERIC_PLACEHOLDER;
}
